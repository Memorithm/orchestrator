#!/usr/bin/env python3
from pathlib import Path

main_path = Path("src/main.rs")
start_path = Path("scripts/start.sh")
install_path = Path("scripts/install-systemd.sh")
readme_path = Path("README.md")

main = main_path.read_text()
start = start_path.read_text()
install = install_path.read_text()
readme = readme_path.read_text()


def replace_once(source: str, old: str, new: str, label: str) -> str:
    count = source.count(old)
    if count != 1:
        raise SystemExit(f"{label}: expected exactly one match, found {count}")
    return source.replace(old, new, 1)


main = replace_once(
    main,
    '''    max_cycles: u64,
    resource_policy: resource::ResourcePolicy,
    retry_policy: state::RetryPolicy,
''',
    '''    max_cycles: u64,
    resource_policy: resource::ResourcePolicy,
    trajectory_max_per_item: usize,
    retry_policy: state::RetryPolicy,
''',
    "run config retention field",
)
main = replace_once(
    main,
    '''            max_cycles: max_cycles_override
                .unwrap_or_else(|| env_u64("ORCHESTRATOR_MAX_CYCLES", 0)),
            resource_policy: resource::ResourcePolicy::from_env()?,
            retry_policy: state::RetryPolicy {
''',
    '''            max_cycles: max_cycles_override
                .unwrap_or_else(|| env_u64("ORCHESTRATOR_MAX_CYCLES", 0)),
            resource_policy: resource::ResourcePolicy::from_env()?,
            trajectory_max_per_item: trajectory::max_files_per_item_from_env()?,
            retry_policy: state::RetryPolicy {
''',
    "retention from environment",
)
main = replace_once(
    main,
    '''    println!(
        "resource load    : <= {:.2} per CPU",
        config.resource_policy.max_load_per_cpu
    );

    let attempt_store = state::AttemptStore::new(
''',
    '''    println!(
        "resource load    : <= {:.2} per CPU",
        config.resource_policy.max_load_per_cpu
    );
    println!(
        "trajectory keep  : {} per work item (0=unlimited)",
        config.trajectory_max_per_item
    );

    let attempt_store = state::AttemptStore::new(
''',
    "retention startup logging",
)
main = replace_once(
    main,
    '''                            &config.model,
                            selection_time,
                        ) {
''',
    '''                            &config.model,
                            selection_time,
                            config.trajectory_max_per_item,
                        ) {
''',
    "journal retention argument",
)

start = replace_once(
    start,
    '''export ORCHESTRATOR_MAX_LOAD_PER_CPU="${ORCHESTRATOR_MAX_LOAD_PER_CPU:-2.0}"

ORGANIZATION="${1:-Memorithm}"
''',
    '''export ORCHESTRATOR_MAX_LOAD_PER_CPU="${ORCHESTRATOR_MAX_LOAD_PER_CPU:-2.0}"
export ORCHESTRATOR_TRAJECTORY_MAX_PER_ITEM="${ORCHESTRATOR_TRAJECTORY_MAX_PER_ITEM:-50}"

ORGANIZATION="${1:-Memorithm}"
''',
    "start retention default",
)
start = replace_once(
    start,
    '''printf 'max_load_per_cpu=%s\\n' "$ORCHESTRATOR_MAX_LOAD_PER_CPU"
printf 'opencode_bridge=isolated-ollama-launch+runtime-permissions\\n'
''',
    '''printf 'max_load_per_cpu=%s\\n' "$ORCHESTRATOR_MAX_LOAD_PER_CPU"
printf 'trajectory_max_per_item=%s\\n' "$ORCHESTRATOR_TRAJECTORY_MAX_PER_ITEM"
printf 'opencode_bridge=isolated-ollama-launch+runtime-permissions\\n'
''',
    "start retention logging",
)

install = replace_once(
    install,
    '''ORCHESTRATOR_MAX_LOAD_PER_CPU=2.0
ORCHESTRATOR_BACKEND_ERROR_MAX=3
''',
    '''ORCHESTRATOR_MAX_LOAD_PER_CPU=2.0
ORCHESTRATOR_TRAJECTORY_MAX_PER_ITEM=50
ORCHESTRATOR_BACKEND_ERROR_MAX=3
''',
    "systemd retention policy",
)

readme = replace_once(
    readme,
    '''ORCHESTRATOR_MAX_LOAD_PER_CPU=2.0
ORCHESTRATOR_MAX_CYCLES=0
''',
    '''ORCHESTRATOR_MAX_LOAD_PER_CPU=2.0
ORCHESTRATOR_TRAJECTORY_MAX_PER_ITEM=50
ORCHESTRATOR_MAX_CYCLES=0
''',
    "README retention environment",
)
readme = replace_once(
    readme,
    '''A PID lock prevents two Orchestrator loops from mutating repositories concurrently. A stale Linux lock is recovered automatically after an unclean process exit.
''',
    '''A PID lock prevents two Orchestrator loops from mutating repositories concurrently. A stale Linux lock is recovered automatically after an unclean process exit.

Each work item keeps at most 50 managed trajectory JSONL files by default. Pruning happens only inside that work item's trajectory directory, removes only filenames generated by Orchestrator, never follows symlinks, and preserves unmanaged JSONL files. Set `ORCHESTRATOR_TRAJECTORY_MAX_PER_ITEM=0` for unlimited retention.
''',
    "README retention behavior",
)

main_path.write_text(main)
start_path.write_text(start)
install_path.write_text(install)
readme_path.write_text(readme)
